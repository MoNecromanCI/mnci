// GeneratedMarker starts every file mnci owns.
const GeneratedMarker = "Generated by mnci"

var unsafeName = regexp.MustCompile(`[^a-z0-9]+`)

// Inspect reads the repository at dir and reports what adopting it involves.
// It changes nothing.
func Inspect(dir, version string, log io.Writer) (Report, error) {
	root, err := filepath.Abs(dir)
	if err != nil {
		return Report{}, err
	}
	r := Report{Root: root, Name: workspaceName(root)}
	exists := func(rel string) bool {
		_, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel)))
		return err == nil
	}
	git := gitclient.New(root)
	switch {
	case !git.IsRepository():
		r.Blockers = append(r.Blockers, Item{Message: "this is not a git repository: mnci versions from tags and finds files through git", Step: "git init, then commit what you have", Blocks: BlocksAdoption})
		return r, nil
	case exists(workspace.FileName):
		r.Blockers = append(r.Blockers, Item{Message: "this is already an mnci workspace", Step: "mnci upgrade, after installing a newer mnci", Blocks: BlocksAdoption})
		return r, nil
	case exists("nx.json"):
		r.Blockers = append(r.Blockers, Item{Message: "this is an Nx workspace: its projects and targets are Nx's to describe", Step: "mnci convert --dry-run", Blocks: BlocksAdoption})
		return r, nil
	}
	status, _ := git.Run("status", "--porcelain")
	r.Clean = strings.TrimSpace(status) == ""
	r.Scope = scopeOf(root, r.Name)
	r.Providers = providersOf(exists)

	cfg, err := previewConfig(r)
	if err != nil {
		return r, err
	}
	s, err := session.Open(session.Options{Dir: root, Version: version, Log: log, Preview: &cfg})
	if err != nil {
		return r, err
	}
	defer s.Close()
	for _, p := range s.Graph.Projects {
		r.Projects = append(r.Projects, ProjectLine{Name: p.Name, Root: p.Root, Language: p.Language, Kind: string(p.Kind), Stack: p.Stack})
	}
	sort.Slice(r.Projects, func(i, j int) bool { return r.Projects[i].Root < r.Projects[j].Root })
	if len(r.Projects) == 0 {
		r.Warnings = append(r.Warnings, Item{Message: "no project found: mnci knows a project by its manifest (package.json in a workspace, go.mod, pyproject.toml)", Step: "mnci add app <name> --lang <language> after --init"})
	}
	for _, f := range release.CheckLineage(s, false) {
		item := Item{Message: f.Message, Step: "see the message", Baseline: f.Baseline}
		if f.Baseline != nil {
			item.Step = "--tags creates " + f.Baseline.Name + " on " + f.Baseline.Target + " (locally; push it yourself)"
		}
		if f.Blocking {
			item.Blocks = BlocksRelease
			r.Blockers = append(r.Blockers, item)
		} else {
			r.Warnings = append(r.Warnings, item)
		}
	}
	for _, path := range []string{cipipeline.GitHubPath, cipipeline.AzurePath, cipipeline.DevcontainerPath} {
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		if err == nil && !strings.Contains(string(body), GeneratedMarker) {
			r.Warnings = append(r.Warnings, Item{Message: path + " is yours, at a path mnci's pipeline uses", Step: "--init keeps it as " + path + ".pre-mnci; move your own steps into the generated file's slots"})
		}
	}
	if deps := rootRuntimeDependencies(root); len(deps) > 0 && hasNodeProjects(r.Projects) {
		r.Warnings = append(r.Warnings, Item{Message: "the root package.json has runtime dependencies (" + strings.Join(deps, ", ") + "): in mnci each project declares what it uses", Step: "mnci install -w <project> <package> for each project that imports it, then drop it from the root"})
	}
	return r, nil
}

// workspaceName is the directory's name made a valid workspace name.
func workspaceName(root string) string {
	name := strings.Trim(unsafeName.ReplaceAllString(strings.ToLower(filepath.Base(root)), "-"), "-")
	if name == "" || name[0] < 'a' || name[0] > 'z' {
		name = "workspace-" + name
	}
	return strings.TrimSuffix(name, "-")
}

// scopeOf is the npm scope the root package.json's name uses, else the
// workspace name's.
func scopeOf(root, name string) string {
	var pkg struct{ Name string }
	if raw, err := os.ReadFile(filepath.Join(root, "package.json")); err == nil && json.Unmarshal(raw, &pkg) == nil && strings.HasPrefix(pkg.Name, "@") {
		return strings.SplitN(pkg.Name, "/", 2)[0]
	}
	return "@" + name
}

// providersOf keeps the CI providers the repository already uses.
func providersOf(exists func(string) bool) []string {
	var out []string
	if exists(".github/workflows") {
		out = append(out, "github")
	}
	if exists(cipipeline.AzurePath) {
		out = append(out, "azure")
	}
	if len(out) == 0 {
		out = []string{"github"}
	}
	return out
}

func previewConfig(r Report) (workspace.Config, error) {
	quoted := make([]string, len(r.Providers))
	for i, p := range r.Providers {
		quoted[i] = fmt.Sprintf("%q", p)
	}
	return workspace.Parse([]byte(fmt.Sprintf("schema = %d\n\n[workspace]\nname = %q\nscope = %q\n\n[ci]\nproviders = [%s]\n", workspace.SchemaVersion, r.Name, r.Scope, strings.Join(quoted, ", "))))
}

func rootRuntimeDependencies(root string) []string {
	var pkg struct{ Dependencies map[string]string }
	raw, err := os.ReadFile(filepath.Join(root, "package.json"))
	if err != nil || json.Unmarshal(raw, &pkg) != nil {
		return nil
	}
	var out []string
	for name := range pkg.Dependencies {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

func hasNodeProjects(projects []ProjectLine) bool {
	for _, p := range projects {
		if p.Language == "node" {
			return true
		}
	}
	return false
}
