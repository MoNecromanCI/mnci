package cipipeline

import (
	"fmt"
	"strings"
)

// GitHubPath is where the GitHub Actions workflow is written.
const GitHubPath = ".github/workflows/ci.yml"

// RenderGitHub renders the model as a GitHub Actions workflow.
func RenderGitHub(m Model) string {
	var b strings.Builder
	b.WriteString(header("#"))
	fmt.Fprintf(&b, `name: ci

on:
  push:
    branches: [%[1]s]
  pull_request:
    branches: [%[1]s]

permissions:
  contents: write
  pull-requests: write

concurrency:
  group: ci-${{ github.ref }}
  cancel-in-progress: ${{ github.event_name == 'pull_request' }}

jobs:
  ci:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
`, m.ReleaseBranch)
	for _, t := range m.Toolchains {
		b.WriteString(githubSetup(t))
	}
	fmt.Fprintf(&b, `      - name: Install mnci
        run: curl -fsSL %s | sh -s -- "$MNCI_VERSION"
        env:
          MNCI_VERSION: %s
`, InstallScriptURL, m.MnciVersion)
	b.WriteString(slot("      ", "before-setup"))
	b.WriteString(`      - name: Setup
        run: mnci ci setup
      - name: Audit
        run: mnci ci audit
      - name: Verify
        run: mnci ci verify
`)
	b.WriteString(slot("      ", "after-verify"))
	b.WriteString(`      - name: Release preview
        if: github.event_name == 'pull_request'
        run: mnci release --dry-run --comment
        env:
          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
`)
	if m.Pack {
		fmt.Fprintf(&b, `      - name: Pack
        if: github.event_name == 'push' && github.ref_name == '%[1]s'
        run: mnci ci pack
      - uses: actions/upload-artifact@v4
        if: github.event_name == 'push' && github.ref_name == '%[1]s'
        with:
          name: drop
          path: dist/drop
          if-no-files-found: ignore
`, m.ReleaseBranch)
	}
	fmt.Fprintf(&b, `      - name: Release
        if: github.event_name == 'push' && github.ref_name == '%s'
        run: mnci ci release
`, m.ReleaseBranch)
	if len(m.Credentials) > 0 {
		b.WriteString("        env:\n")
		for _, c := range m.Credentials {
			fmt.Fprintf(&b, "          %s: ${{ secrets.%s }}\n", c.Env, c.Env)
		}
	}
	return b.String()
}

func header(comment string) string {
	return comment + " Generated by mnci from the workspace's projects. `mnci add` and `mnci ci generate`\n" +
		comment + " rewrite this file: put your own steps between the mnci:slot markers, which are kept.\n"
}

func slot(indent, name string) string {
	return indent + "# mnci:slot " + name + "\n" + indent + "# mnci:slot-end " + name + "\n"
}
